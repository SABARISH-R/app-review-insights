"""Write CSV outputs, charts and a Markdown report."""
from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from .load import CleaningSummary  # noqa: E402


def _md_table(df: pd.DataFrame, pct_cols=(), float_cols=()) -> str:
    view = df.copy()
    for c in pct_cols:
        view[c] = (view[c] * 100).round(1).astype(str) + "%"
    for c in float_cols:
        view[c] = view[c].round(3)
    headers = "| " + " | ".join(view.columns) + " |"
    sep = "|" + "|".join("---" for _ in view.columns) + "|"
    rows = ["| " + " | ".join(str(v) for v in r) + " |" for r in view.itertuples(index=False)]
    return "\n".join([headers, sep, *rows])


def write_report(out_dir, df, summary: CleaningSummary, metrics, trends, dist, min_mentions: int,
                 title_suffix: str = "", banner: str = "") -> Path:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    metrics.to_csv(out / "theme_metrics.csv", index=False)  # load into Power BI / Tableau
    if not trends.empty:
        trends.to_csv(out / "monthly_trends.csv", index=False)

    # Chart 1: rating distribution
    fig, ax = plt.subplots(figsize=(5, 3))
    ax.bar(dist.index.astype(str), dist.values, color="#1F3A5F")
    ax.set_xlabel("Star rating")
    ax.set_ylabel("Reviews")
    ax.set_title(f"Rating distribution{title_suffix}", fontsize=9)
    fig.tight_layout()
    fig.savefig(out / "rating_distribution.png", dpi=150)
    plt.close(fig)

    # Chart 2: impact by theme
    shown = metrics[metrics["reliable"]].head(8).iloc[::-1]
    if not shown.empty:
        fig, ax = plt.subplots(figsize=(6, 3.5))
        ax.barh(shown["theme"], shown["impact"], color="#C0392B")
        ax.set_xlabel("Estimated rating points lost (impact)")
        ax.set_title(f"Top pain points by impact{title_suffix}", fontsize=9)
        fig.tight_layout()
        fig.savefig(out / "top_pain_points.png", dpi=150)
        plt.close(fig)

    # Chart 3: monthly trend
    if not trends.empty:
        fig, ax = plt.subplots(figsize=(6, 3))
        ax.plot(trends["month"], trends["avg_rating"], marker="o", color="#1F3A5F")
        ax.set_ylabel("Average rating")
        ax.set_title(f"Average rating by month{title_suffix}", fontsize=9)
        fig.autofmt_xdate()
        fig.tight_layout()
        fig.savefig(out / "monthly_rating.png", dpi=150)
        plt.close(fig)

    lines = ([banner, ""] if banner else []) + [
        "# Review analysis report",
        "",
        "_Generated by ReviewLens. Read docs/METHODOLOGY.md for definitions and limitations._",
        "",
        "## Dataset",
        f"- Rows in file: {summary.rows_in}",
        f"- Rows analysed: {summary.rows_out}",
        f"- Dropped: {summary.dropped_missing} missing text/rating, "
        f"{summary.dropped_bad_rating} invalid rating, {summary.dropped_duplicates} duplicates",
        f"- Average rating: {df['rating'].mean():.2f}",
        f"- Share of 1-2 star reviews: {(df['rating'] <= 2).mean():.1%}",
        "",
        "![Rating distribution](rating_distribution.png)",
        "",
        f"## Pain points (themes with at least {min_mentions} mentions are marked reliable)",
        "",
        _md_table(metrics, pct_cols=("share_of_reviews", "share_of_low_rated"),
                  float_cols=("avg_rating_when_mentioned", "rating_gap", "impact")),
        "",
    ]
    if (out / "top_pain_points.png").exists():
        lines += ["![Top pain points](top_pain_points.png)", ""]
    if (out / "monthly_rating.png").exists():
        lines += ["## Trend", "", "![Monthly rating](monthly_rating.png)", ""]
    path = out / "report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
